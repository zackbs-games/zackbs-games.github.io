function getFloorHeight(px, pz, halfWidth = PLAYER_WIDTH) {
  const x0 = Math.floor(px - halfWidth + 0.001);
  const x1 = Math.floor(px + halfWidth - 0.001);
  const z0 = Math.floor(pz - halfWidth + 0.001);
  const z1 = Math.floor(pz + halfWidth - 0.001);
  let h = 0;
  for (let x = x0; x <= x1; x++) {
    for (let z = z0; z <= z1; z++) {
      h = Math.max(h, blockHeightMap.get(`${x},${z}`) ?? 0);
    }
  }
  return h;
}

