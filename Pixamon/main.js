function generateChunkCreatures(cx, cz) {
  const count = 2 + Math.floor(chunkRand(cx, cz, 0) * 3); // 2–4
  const result = [];
  for (let i = 0; i < count; i++) {
    const type = creatureTypes[Math.floor(chunkRand(cx, cz, i * 5 + 1) * creatureTypes.length)];
    const level = 1 + Math.floor(chunkRand(cx, cz, i * 5 + 2) * 8);
    const wx = cx * chunkSize + Math.floor(chunkRand(cx, cz, i * 5 + 3) * chunkSize);
    const wz = cz * chunkSize + Math.floor(chunkRand(cx, cz, i * 5 + 4) * chunkSize);
    const hp = 10 + level * 3;
    const y = getTerrainHeight(wx, wz);
    result.push({
      name: type.name, level,
      hp, maxHp: hp,
      attack: type.baseAttack + level,
      position: [wx, y, wz],
      velocityY: 0,
      color: type.color,
      targetX: wx, targetZ: wz,
      wanderTimer: chunkRand(cx, cz, i * 5 + 5) * 3,
      yaw: chunkRand(cx, cz, i * 5 + 6) * Math.PI * 2,
    });
  }
  return result;
}

function updateCreatures(delta) {
  for (const c of creatures) {
    // Wander AI
    c.wanderTimer -= delta;
    if (c.wanderTimer <= 0) {
      const angle = Math.random() * Math.PI * 2;
      const dist = 3 + Math.random() * 8;
      c.targetX = c.position[0] + Math.cos(angle) * dist;
      c.targetZ = c.position[2] + Math.sin(angle) * dist;
      c.wanderTimer = 2 + Math.random() * 4;
    }
    const dx = c.targetX - c.position[0];
    const dz = c.targetZ - c.position[2];
    const d = Math.sqrt(dx * dx + dz * dz);
    if (d > 0.5) {
      c.yaw = Math.atan2(dx, dz);
      const mx = (dx / d) * 1.5 * delta;
      const mz = (dz / d) * 1.5 * delta;
      const testX = c.position[0] + mx;
      if (getFloorHeight(testX, c.position[2], CREATURE_WIDTH) <= c.position[1] + CREATURE_STEP_HEIGHT) {
        c.position[0] = testX;
      }
      const testZ = c.position[2] + mz;
      if (getFloorHeight(c.position[0], testZ, CREATURE_WIDTH) <= c.position[1] + CREATURE_STEP_HEIGHT) {
        c.position[2] = testZ;
      }
    }
    // Gravity
    c.velocityY += GRAVITY * delta;
    c.position[1] += c.velocityY * delta;
    const floor = getFloorHeight(c.position[0], c.position[2], CREATURE_WIDTH);
    if (c.position[1] <= floor) {
      c.position[1] = floor;
      c.velocityY = 0;
    }
  }
}

function placeTree(instances, wx, baseY, wz) {
  const trunkH = 4;
  for (let dy = 0; dy < trunkH; dy++) {
    addBlock(instances, [wx, baseY + dy, wz], blockTiles.wood);
  }
  const topY = baseY + trunkH;
  // wide leaf ring at trunk top - 1 (5×5 minus corners)
  for (let dx = -2; dx <= 2; dx++) for (let dz = -2; dz <= 2; dz++) {
    if (Math.abs(dx) === 2 && Math.abs(dz) === 2) continue;
    addBlock(instances, [wx + dx, topY - 1, wz + dz], blockTiles.leaves);
  }
  // 3×3 cap for two top layers
  for (let dy = 0; dy <= 1; dy++) {
    for (let dx = -1; dx <= 1; dx++) for (let dz = -1; dz <= 1; dz++) {
      addBlock(instances, [wx + dx, topY + dy, wz + dz], blockTiles.leaves);
    }
  }
}

function buildChunkInto(instances, chunkX, chunkZ) {
  const offsetX = chunkX * chunkSize;
  const offsetZ = chunkZ * chunkSize;
  for (let x = 0; x < chunkSize; x++) {
    for (let z = 0; z < chunkSize; z++) {
      const wx = offsetX + x;
      const wz = offsetZ + z;
      const height = Math.max(1, Math.floor(terrainNoise(wx, wz) * 14));
      const top = height >= 12 ? blockTiles.snow : blockTiles.grass;
      for (let y = 0; y < height; y++) {
        let tileIndex = y === height - 1 ? top : y < 2 ? blockTiles.stone : blockTiles.dirt;
        addBlock(instances, [wx, y, wz], tileIndex);
      }
    }
  }
  // Scatter trees on grass terrain
  const numTrees = 3 + Math.floor(hash2(chunkX * 7 + 1, chunkZ * 7 + 1) * 5);
  for (let i = 0; i < numTrees; i++) {
    const tx = 3 + Math.floor(hash2(chunkX * 100 + i * 13, chunkZ * 100 + 7) * (chunkSize - 6));
    const tz = 3 + Math.floor(hash2(chunkX * 100 + 3, chunkZ * 100 + i * 17) * (chunkSize - 6));
    const wx = offsetX + tx, wz = offsetZ + tz;
    const height = Math.max(1, Math.floor(terrainNoise(wx, wz) * 14));
    if (height < 3 || height >= 12) continue;
    placeTree(instances, wx, height, wz);
  }
}

