function buildPipeline(device, shaderModule) {
  const bindGroupLayout = device.createBindGroupLayout({
    entries: [
      { binding: 0, visibility: GPUShaderStage.VERTEX,   buffer:  { type: 'uniform' } },
      { binding: 1, visibility: GPUShaderStage.FRAGMENT, sampler: { type: 'filtering' } },
      { binding: 2, visibility: GPUShaderStage.FRAGMENT, texture: { sampleType: 'float' } },
      { binding: 3, visibility: GPUShaderStage.FRAGMENT, texture: { sampleType: 'float' } },
    ]
  });

  const pipelineLayout = device.createPipelineLayout({
    bindGroupLayouts: [bindGroupLayout]
  });

  const pipeline = device.createRenderPipeline({
    layout: pipelineLayout,
    vertex: {
      module: shaderModule,
      entryPoint: 'main',
      buffers: [
        {
          arrayStride: 3 * 4,
          attributes: [
            { shaderLocation: 0, offset: 0, format: 'float32x3' },
          ],
        },
        {
          arrayStride: 3 * 4,
          attributes: [
            { shaderLocation: 1, offset: 0, format: 'float32x3' },
          ],
        },
        {
          arrayStride: 21 * 4,
          stepMode: 'instance',
          attributes: [
            { shaderLocation: 2, offset:  0, format: 'float32x4' },
            { shaderLocation: 3, offset: 16, format: 'float32x4' },
            { shaderLocation: 4, offset: 32, format: 'float32x4' },
            { shaderLocation: 5, offset: 48, format: 'float32x4' },
            { shaderLocation: 6, offset: 64, format: 'float32x4' },
            { shaderLocation: 7, offset: 80, format: 'float32'   },
          ],
        },
      ],
    },
    fragment: {
      module: shaderModule,
      entryPoint: 'frag',
      targets: [{ format, blend: {
        color: { srcFactor: 'src-alpha', dstFactor: 'one-minus-src-alpha', operation: 'add' },
        alpha: { srcFactor: 'one',       dstFactor: 'zero',                operation: 'add' },
      }}],
    },
    primitive: {
      topology: 'triangle-list',
      cullMode: 'none',
      frontFace: 'cw',
    },
    depthStencil: {
      format: 'depth24plus',
      depthWriteEnabled: true,
      depthCompare: 'less',
    },
  });
  return { pipeline, bindGroupLayout };
}

function createBuffers(device, cube) {
  vertexBuffer = device.createBuffer({
    size: cube.positions.byteLength,
    usage: GPUBufferUsage.VERTEX | GPUBufferUsage.COPY_DST,
    mappedAtCreation: true,
  });
  new Float32Array(vertexBuffer.getMappedRange()).set(cube.positions);
  vertexBuffer.unmap();

  normalBuffer = device.createBuffer({
    size: cube.normals.byteLength,
    usage: GPUBufferUsage.VERTEX | GPUBufferUsage.COPY_DST,
    mappedAtCreation: true,
  });
  new Float32Array(normalBuffer.getMappedRange()).set(cube.normals);
  normalBuffer.unmap();

  indexBuffer = device.createBuffer({
    size: cube.indices.byteLength,
    usage: GPUBufferUsage.INDEX | GPUBufferUsage.COPY_DST,
    mappedAtCreation: true,
  });
  new Uint16Array(indexBuffer.getMappedRange()).set(cube.indices);
  indexBuffer.unmap();

  uniformBuffer = device.createBuffer({
    size: 16 * 4,
    usage: GPUBufferUsage.UNIFORM | GPUBufferUsage.COPY_DST,
  });

  instanceBuffer = device.createBuffer({
    size: 1000000 * 84,
    usage: GPUBufferUsage.VERTEX | GPUBufferUsage.COPY_DST,
  });
}

function updateInstanceBuffer() {
  const data = new Float32Array(worldInstances.length * 21);
  let offset = 0;
  for (const inst of worldInstances) {
    data.set(inst.model, offset); offset += 16;
    // color unused for terrain (atlas supplies colour); write zeros
    offset += 4;
    data[offset] = inst.tileIndex; offset += 1;
  }
  device.queue.writeBuffer(instanceBuffer, 0, data);
}

function createUniformBindGroup(device, bindGroupLayout, atlasSampler, colTexView, nrmTexView) {
  return device.createBindGroup({
    layout: bindGroupLayout,
    entries: [
      { binding: 0, resource: { buffer: uniformBuffer } },
      { binding: 1, resource: atlasSampler },
      { binding: 2, resource: colTexView },
      { binding: 3, resource: nrmTexView },
    ],
  });
}

async function createAtlasTexture(device) {
  const T = 16, COLS = 10, SZ = T * COLS; // 160×160

  function prng(seed) {
    let s = (seed ^ 0xdeadbeef) >>> 0;
    return () => {
      s = Math.imul(s ^ (s >>> 16), 0x45d9f3b) >>> 0;
      s = Math.imul(s ^ (s >>> 16), 0x45d9f3b) >>> 0;
      return s / 0xffffffff;
    };
  }

  // --- Colour atlas ---
  const colCanvas = document.createElement('canvas');
  colCanvas.width = colCanvas.height = SZ;
  const cctx = colCanvas.getContext('2d');
  const cd = cctx.createImageData(SZ, SZ);
  const c = cd.data;

  function cpx(tile, x, y, r, g, b, a = 255) {
    const i = (y * SZ + tile * T + x) * 4;
    c[i] = r; c[i+1] = g; c[i+2] = b; c[i+3] = a;
  }

  // tile 0: grass_top
  { const r = prng(0); for (let y = 0; y < T; y++) for (let x = 0; x < T; x++) {
    const n = r() * 40 - 20;
    cpx(0, x, y, 46+n|0, 158+n|0, 38+n*0.5|0);
  }}
  // tile 1: grass_side
  { const r = prng(1); for (let y = 0; y < T; y++) for (let x = 0; x < T; x++) {
    const n = r() * 26 - 13;
    if (y < 4) cpx(1, x, y, 46+n|0, 158+n|0, 38+n*0.5|0);
    else        cpx(1, x, y, 107+n|0, 71+n|0, 25+n*0.5|0);
  }}
  // tile 2: dirt
  { const r = prng(2); for (let y = 0; y < T; y++) for (let x = 0; x < T; x++) {
    const n = r() * 30 - 15;
    cpx(2, x, y, 122+n|0, 76+n|0, 30+n*0.5|0);
  }}
  // tile 3: stone
  { const r = prng(3); for (let y = 0; y < T; y++) for (let x = 0; x < T; x++) {
    const n = r() * 30 - 15;
    const v = 132+n|0;
    cpx(3, x, y, v, v, v+10|0);
  }}
  // tile 4: snow_top
  { const r = prng(4); for (let y = 0; y < T; y++) for (let x = 0; x < T; x++) {
    const n = r() * 14 - 7;
    const v = 235+n|0;
    cpx(4, x, y, v, v, Math.min(255, v+10)|0);
  }}
  // tile 5: snow_side
  { const r = prng(5); for (let y = 0; y < T; y++) for (let x = 0; x < T; x++) {
    const n = r() * 14 - 7;
    if (y < 4) { const v = 235+n|0; cpx(5, x, y, v, v, Math.min(255,v+10)|0); }
    else        { const v = 132+n|0; cpx(5, x, y, v, v, v+10|0); }
  }}
  // tile 6: water (alpha 0.88)
  { const r = prng(6); for (let y = 0; y < T; y++) for (let x = 0; x < T; x++) {
    const n = r() * 20 - 10;
    const sh = Math.sin((x+y)*0.8)*12|0;
    cpx(6, x, y, Math.max(0,20+n)|0, Math.min(255,97+sh+n)|0, Math.min(255,199+sh+n)|0, 224);
  }}
  // tile 7: wood (bark — vertical grain on sides, same texture all faces)
  { const r = prng(7); for (let y = 0; y < T; y++) for (let x = 0; x < T; x++) {
    const grain = Math.sin(x * 1.8) * 18 | 0;
    const n = r() * 16 - 8;
    cpx(7, x, y, Math.min(255, 101 + grain + n)|0, Math.min(255, 58 + grain*0.5 + n)|0, Math.max(0, 18 + n)|0);
  }}
  // tile 8: leaves (dappled green, slightly transparent edges)
  { const r = prng(8); for (let y = 0; y < T; y++) for (let x = 0; x < T; x++) {
    const n = r() * 40 - 20;
    const sparse = r() > 0.12 ? 255 : 180;
    cpx(8, x, y, Math.max(0, 28 + n)|0, Math.min(255, 105 + n)|0, Math.max(0, 22 + n*0.4)|0, sparse);
  }}
  // tile 9: plank (horizontal grain, lighter processed wood)
  { const r = prng(9); for (let y = 0; y < T; y++) for (let x = 0; x < T; x++) {
    const grain = Math.sin(y * 1.6) * 22 | 0;
    const line = (y % 4 === 0) ? -18 : 0;
    const n = r() * 12 - 6;
    cpx(9, x, y, Math.min(255, 160 + grain + line + n)|0, Math.min(255, 100 + grain*0.5 + line + n)|0, Math.max(0, 38 + line + n)|0);
  }}

  cctx.putImageData(cd, 0, 0);
  const colBmp = await createImageBitmap(colCanvas);
  const colTex = device.createTexture({ size:[SZ,SZ], format:'rgba8unorm',
    usage: GPUTextureUsage.TEXTURE_BINDING|GPUTextureUsage.COPY_DST|GPUTextureUsage.RENDER_ATTACHMENT });
  device.queue.copyExternalImageToTexture({ source: colBmp }, { texture: colTex }, [SZ, SZ]);

  // --- Normal-map atlas ---
  const nrmCanvas = document.createElement('canvas');
  nrmCanvas.width = nrmCanvas.height = SZ;
  const nctx = nrmCanvas.getContext('2d');
  const nd2 = nctx.createImageData(SZ, SZ);
  const n = nd2.data;

  function npx(tile, x, y, nx, ny, nz) {
    const i = (y * SZ + tile * T + x) * 4;
    n[i]   = (nx * 0.5 + 0.5) * 255 | 0;
    n[i+1] = (ny * 0.5 + 0.5) * 255 | 0;
    n[i+2] = (nz * 0.5 + 0.5) * 255 | 0;
    n[i+3] = 255;
  }

  function buildNrmTile(tile, hFn) {
    const h = new Float32Array(T * T);
    for (let y = 0; y < T; y++) for (let x = 0; x < T; x++) h[y*T+x] = hFn(x, y);
    for (let y = 0; y < T; y++) for (let x = 0; x < T; x++) {
      const dxH = h[y*T + (x+1)%T] - h[y*T+x];
      const dyH = h[((y+1)%T)*T+x] - h[y*T+x];
      const len = Math.sqrt(dxH*dxH + dyH*dyH + 1);
      npx(tile, x, y, -dxH/len, -dyH/len, 1/len);
    }
  }

  buildNrmTile(0, (x,y) => { const r=prng(200); for(let i=0;i<y*T+x;i++)r(); return r()*0.8; });
  buildNrmTile(1, (x,y) => Math.sin(x*1.2)*0.4 + prng(201+y*T+x)()*0.2);
  buildNrmTile(2, (x,y) => { const r=prng(300); for(let i=0;i<y*T+x;i++)r(); return r()*0.5; });
  buildNrmTile(3, (x,y) => { const r=prng(400); for(let i=0;i<y*T+x;i++)r(); const v=r(); return v<0.15?0:v*1.2; });
  buildNrmTile(4, (x,y) => Math.sin(x*0.5+y*0.3)*0.3 + prng(500+y*T+x)()*0.2);
  buildNrmTile(5, (x,y) => Math.sin(x*0.8)*0.5 + prng(600+y*T+x)()*0.15);
  buildNrmTile(6, (x,y) => Math.sin((x+y)*0.7)*0.6);
  buildNrmTile(7, (x,y) => Math.sin(x * 1.8) * 0.5 + prng(700 + y * T + x)() * 0.1);
  buildNrmTile(8, (x,y) => { const r = prng(800); for (let i = 0; i < y * T + x; i++) r(); return r() * 0.6; });
  buildNrmTile(9, (x,y) => Math.sin(y * 1.6) * 0.4 + prng(900 + y * T + x)() * 0.1);

  nctx.putImageData(nd2, 0, 0);
  const nrmBmp = await createImageBitmap(nrmCanvas);
  const nrmTex = device.createTexture({ size:[SZ,SZ], format:'rgba8unorm',
    usage: GPUTextureUsage.TEXTURE_BINDING|GPUTextureUsage.COPY_DST|GPUTextureUsage.RENDER_ATTACHMENT });
  device.queue.copyExternalImageToTexture({ source: nrmBmp }, { texture: nrmTex }, [SZ, SZ]);

  const sampler = device.createSampler({ minFilter:'nearest', magFilter:'nearest' });
  return { colTex, nrmTex, sampler, colCanvas };
}

