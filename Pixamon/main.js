  const rFootX = rKneeX - fx * 0.55 * Math.sin(rLowerAngle);
  const rFootY = rKneeY - 0.55 * Math.cos(rLowerAngle);
  const rFootZ = rKneeZ - fz * 0.55 * Math.sin(rLowerAngle);
