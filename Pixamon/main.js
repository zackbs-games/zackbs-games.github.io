function castRay(maxDist = 6) {
  const ey = player.position[1] + EYE_HEIGHT - player.crouchAmt * 0.6;
  // World-space eye position (used for distance checks and reporting)
  const owx = player.position[0], owy = ey, owz = player.position[2];
  const cp = Math.cos(player.pitch), sp = Math.sin(player.pitch);
  const dx = Math.cos(player.yaw) * cp;
  const dy = sp;
  const dz = Math.sin(player.yaw) * cp;

  // Blocks are centered at integers, so their boundaries fall at half-integers.
  // Shift the origin by +0.5 so Math.floor maps correctly to block indices.
  const ox = owx + 0.5, oy = owy + 0.5, oz = owz + 0.5;

  let ix = Math.floor(ox), iy = Math.floor(oy), iz = Math.floor(oz);
  const sx = dx > 0 ? 1 : -1, sy = dy > 0 ? 1 : -1, sz = dz > 0 ? 1 : -1;
  const tdx = Math.abs(1 / dx), tdy = Math.abs(1 / dy), tdz = Math.abs(1 / dz);
  let tx = ((dx > 0 ? ix + 1 : ix) - ox) / dx;
  let ty = ((dy > 0 ? iy + 1 : iy) - oy) / dy;
  let tz = ((dz > 0 ? iz + 1 : iz) - oz) / dz;
  let face = [0, 0, 0];

  for (let i = 0; i < 80; i++) {
    const inst = worldInstances.find(w => w.model[12] === ix && w.model[13] === iy && w.model[14] === iz);
    if (inst) return { pos: [ix, iy, iz], face, inst };
    if (Math.hypot(ix - owx, iy - owy, iz - owz) > maxDist) break;
    if (tx < ty && tx < tz) {
      ix += sx; face = [-sx, 0, 0]; tx += tdx;
    } else if (ty < tz) {
      iy += sy; face = [0, -sy, 0]; ty += tdy;
    } else {
      iz += sz; face = [0, 0, -sz]; tz += tdz;
    }
  }
  return null;
}

function placeBlock() {
  const hit = castRay();
  if (!hit) return;
  const key = hotbarSlots[player.selectedSlot];
  if (!key || inventory[key] <= 0) return;
  if (blockTiles[key] === undefined) return;
  const p = [hit.pos[0] + hit.face[0], hit.pos[1] + hit.face[1], hit.pos[2] + hit.face[2]];
  const pp = player.position;
  if (p[0] === Math.round(pp[0]) && p[2] === Math.round(pp[2]) && (p[1] === Math.floor(pp[1]) || p[1] === Math.floor(pp[1]) + 1)) return;
  addBlock(worldInstances, p, blockTiles[key]);
  inventory[key]--;
  updateInstanceBuffer();
  rebuildHeightMap();
}

function updateMining(delta) {
  if (!mouseDown.left) { miningState = null; return; }
  const hit = castRay();
  if (!hit) { miningState = null; return; }
  const [hx, hy, hz] = hit.pos;
  if (!miningState || miningState.pos[0] !== hx || miningState.pos[1] !== hy || miningState.pos[2] !== hz) {
    const key = TILE_KEY[hit.inst.tileIndex];
    let duration = MINE_DURATION[key] ?? 2.0;
    const heldKey = hotbarSlots[player.selectedSlot];
    const toolDef = heldKey && TOOL_SPEED[heldKey];
    if (toolDef && toolDef.blocks.includes(key) && inventory[heldKey] > 0) {
      duration *= toolDef.mult;
    }
    miningState = { pos: hit.pos, progress: 0, duration, key, inst: hit.inst };
  }
  miningState.progress += delta;
  if (miningState.progress >= miningState.duration) {
    if (miningState.key && inventory[miningState.key] !== undefined) inventory[miningState.key]++;
    const idx = worldInstances.indexOf(miningState.inst);
    if (idx >= 0) worldInstances.splice(idx, 1);
    updateInstanceBuffer();
    rebuildHeightMap();
    miningState = null;
  }
}

